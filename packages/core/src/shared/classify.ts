/**
 * Decides what a changed file means for the iOS build: reinstall dependencies,
 * re-run `cap sync`, rebuild native code, or just refresh web assets.
 */

export type ChangeKind = 'deps' | 'pods' | 'native' | 'capconfig' | 'web' | 'other';

export interface ClassifyContext {
  /** POSIX path from the synced root to the Capacitor project ('' if same). */
  projectRel: string;
  /** Web assets dir relative to the Capacitor project, e.g. "dist" or "www". */
  webDir: string;
  /** iOS platform dir relative to the Capacitor project (default "ios"). */
  iosDir?: string;
}

const DEPS_FILES = new Set([
  'package.json',
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'pnpm-workspace.yaml',
  'bun.lockb',
  'bun.lock',
  '.npmrc',
  '.yarnrc',
  '.yarnrc.yml',
  '.pnpmfile.cjs',
]);

const NATIVE_EXTENSIONS = /\.(swift|m|mm|h|hpp|c|cc|cpp|podspec|xcconfig|plist|storyboard|xib|entitlements|xcprivacy|strings|stringsdict|xcstrings|metal|modulemap)$/i;
const NATIVE_DIRS = /(^|\/)[^/]+\.(xcassets|xcodeproj|xcworkspace|xcframework|framework|bundle|lproj)(\/|$)/i;
const POD_FILES = /(^|\/)(Podfile|Podfile\.lock|Package\.swift|Package\.resolved)$/;
const CAP_CONFIG = /^capacitor\.config\.(ts|js|mjs|cjs|json)$/;

function trimSlashes(p: string): string {
  return p.replace(/^\/+|\/+$/g, '');
}

export function classifyChange(rel: string, ctx: ClassifyContext): ChangeKind {
  const projectRel = trimSlashes(ctx.projectRel);
  const webDir = trimSlashes(ctx.webDir || 'www');
  const iosDir = trimSlashes(ctx.iosDir || 'ios');
  const base = rel.slice(rel.lastIndexOf('/') + 1);

  const inProject = projectRel === '' || rel === projectRel || rel.startsWith(`${projectRel}/`);
  const local = inProject ? (projectRel === '' ? rel : rel.slice(projectRel.length + 1)) : null;

  if (DEPS_FILES.has(base)) return 'deps';

  if (local !== null) {
    if (CAP_CONFIG.test(local)) return 'capconfig';
    if (local === webDir || local.startsWith(`${webDir}/`)) return 'web';
    if (local.startsWith(`${iosDir}/`)) {
      const inIos = local.slice(iosDir.length + 1);
      // Generated by `cap copy`; never a reason to rebuild.
      if (/^App\/App\/(public\/|capacitor\.config\.json$|config\.xml$)/.test(inIos)) return 'web';
      if (POD_FILES.test(inIos)) return 'pods';
      return 'native';
    }
  }

  if (POD_FILES.test(rel)) return 'pods';
  if (NATIVE_DIRS.test(rel) || NATIVE_EXTENSIONS.test(base)) return 'native';
  return 'other';
}

export interface ChangeSummary {
  deps: boolean;
  pods: boolean;
  native: boolean;
  capconfig: boolean;
  web: boolean;
  other: boolean;
}

export function summarizeChanges(paths: Iterable<string>, ctx: ClassifyContext): ChangeSummary {
  const summary: ChangeSummary = { deps: false, pods: false, native: false, capconfig: false, web: false, other: false };
  for (const p of paths) summary[classifyChange(p, ctx)] = true;
  return summary;
}
